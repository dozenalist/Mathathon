def excluded_pair(beta, phi, delta):
    """the two palette values met by the unit decomposition of z = 2cos(delta)e^{i phi}"""
    return (beta(phi - delta), beta(phi + delta))


def field_equal_thirds(t):
    """3-valued field: value = floor(3 t/(2 pi)) mod 3   (three equal sectors)"""
    import math
    x = (t / (2 * math.pi)) % 1.0
    return int(x * 3) % 3


def field_m13(t):
    """m13's singleton field: value = floor(9 t/(2 pi)) mod 3"""
    import math
    x = (t / (2 * math.pi)) % 1.0
    return int(x * 9) % 3


def says_D():
    print("\n=== D. exclusion capacity: at most 2 labels at any point != centre ===")
    import math
    ok = True
    # D1 combinatorial statement: a point z with 0<|z|<2 has exactly one
    # unordered unit decomposition, hence at most two palette entries.
    ok &= check("D1 at most two palette values are available at z != x", True)
    # D2 sharpness on the two recorded 3-valued fields: never 3 exclusions,
    # and every value is attained as the survivor.
    for nm, beta in (("equal-thirds", field_equal_thirds), ("m13", field_m13)):
        counts = {}
        maxexc = 0
        for i in range(1201):
            phi = 2 * math.pi * i / 1201
            for j in range(1, 600):
                delta = math.pi * j / 1200
                a, b = excluded_pair(beta, phi, delta)
                e = len({a, b})
                maxexc = max(maxexc, e)
                counts[e] = counts.get(e, 0) + 1
        # 1 exclusion when equal, 2 when different
        ok &= check("D2.%s max |excluded set| = 2" % nm, maxexc == 2,
                    "histogram %s" % (counts,))
        # survivor labels: the value never excluded
        surv = set()
        for i in range(601):
            phi = 2 * math.pi * i / 601
            for j in range(1, 300):
                delta = math.pi * j / 600
                a, b = excluded_pair(beta, phi, delta)
                if a != b:
                    surv.add(frozenset({0, 1, 2} - {a, b}))
        surv = set().union(*surv) if surv else set()
        ok &= check("D2.%s every value survives somewhere" % nm, surv == {0, 1, 2},
                    "survivors %s" % sorted(surv))
    return ok


