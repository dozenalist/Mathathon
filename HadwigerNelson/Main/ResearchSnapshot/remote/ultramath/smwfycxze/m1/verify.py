"""
verify.py -- exact verification for the note `proof.md`
(swarm smwfy c xze, member m1).

Everything decided here uses exact integer / rational arithmetic.
Where a sign of a real algebraic number is decided, two independent
procedures are run and must agree:

  PROC-1  rigorous rational interval arithmetic on the four-dimensional
          Q-basis {1, sqrt3, sqrt11, sqrt33} (rounding-outwards Fractions);
  PROC-2  exact algebraic arithmetic in Q(sqrt3, sqrt11, sqrt33) with the
          sign decided by nested rational brackets of sqrt3 and sqrt11
          computed from two *different* bracket families (squaring
          certificates vs. the continued fraction of sqrt3 / sqrt11).

Blocks:
  A  unique unit decomposition of z  (Lemma 1 of proof.md)
  B  the three trigonometric identities underlying the k=5 calibration
  C  the k=5 calibration: the region where *both* outsiders are excluded is
     exactly the paper's (8.4); the seven Moser vertices lie strictly inside
     it (re-verification of the paper's Lemma 8.9, two methods)
  D  exclusion capacity: at one centre at most 2 labels can be excluded
     (Theorem 2 / Corollary 3), checked on the sharp 3-valued fields
  E  the R-orbit dichotomy counts at k=6 (S_1, triangle centres)
  F  vacuity tests on the recorded countermodels (m13, m15 shapes)

Run:  python3 verify.py      (exit status 0 iff every check passes)
"""

