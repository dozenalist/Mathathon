"""The interface state system over the full 12-position dihedral orbit of directions.

(5.7) says P_x(f) cap P_x(Rf) = empty for a.e. f.  R has order 6, so the orbit of a
generic direction under the group generated by R and -1 is

    f_0 = e, f_1 = Re, ..., f_5 = R^5 e, f_6 = -e = R^6 e, ..., f_11 = R^11 e,

twelve directions with f_12 = f_0, and (5.7) applied at each f_i gives
P(f_i) cap P(f_{i+1}) = empty cyclically over the twelve positions.  The paper's own
five-cycle argument (Prop 8.2) uses the antipodal step, so the twelve-position system is
the one the method actually has available.

Signs: sign(f_i . v_j) = sign(cos(theta_j - i pi/3)) is 6-periodic in i, so the same
cell datum c in {0..5}^ell describes every geometry.
"""
from itertools import product, combinations
from interface_csp import COS_SIGN

NPOS = 12


def sign_matrix(ell, c):
    return [[COS_SIGN[(c[j] + 1 - i) % 6] for j in range(ell)] for i in range(NPOS)]


def allowed_sets(ell, k, sig_i):
    T = (1 << ell) - 1
    U = ((1 << k) - 1) ^ T
    O = I = 0
    for j in range(ell):
        if sig_i[(j - 1) % ell] == -1 and sig_i[j] == -1:
            O |= 1 << j
        if sig_i[(j - 1) % ell] == 1 and sig_i[j] == 1:
            I |= 1 << j
    return O | U, I | U


def admissible_masks(ell, k, sig_i):
    O, I = allowed_sets(ell, k, sig_i)
    out = []
    for r in range(1, k - 2):
        for comb in combinations(range(k), r):
            p = 0
            for i in comb:
                p |= 1 << i
            if (p & O) and (p & I):
                out.append(p)
    return out


def sat_geometry(ell, k, c):
    sig = sign_matrix(ell, c)
    adm = [admissible_masks(ell, k, sig[i]) for i in range(NPOS)]
    if any(not a for a in adm):
        return False
    pos = {p: n for n, p in enumerate(adm[0])}
    reach = {p: 1 << n for p, n in pos.items()}
    for i in range(1, NPOS):
        nxt = {}
        for q in adm[i]:
            acc = 0
            for p, v in reach.items():
                if not (p & q):
                    acc |= v
            if acc:
                nxt[q] = acc
        reach = nxt
        if not reach:
            return False
    for q, v in reach.items():
        for p, n in pos.items():
            if not (p & q) and (v >> n) & 1:
                return True
    return False


def witness(ell, k, c):
    sig = sign_matrix(ell, c)
    adm = [admissible_masks(ell, k, sig[i]) for i in range(NPOS)]

    def bt(i, sol):
        if i == NPOS:
            return not (sol[NPOS - 1] & sol[0])
        for q in adm[i]:
            if not (q & sol[i - 1]):
                sol.append(q)
                if bt(i + 1, sol):
                    return True
                sol.pop()
        return False

    for s in adm[0]:
        sol = [s]
        if bt(1, sol):
            return [[i for i in range(k) if (p >> i) & 1] for p in sol]
    return None


def scan(ell, k):
    total = 6 ** (ell - 1)
    sat = 0
    first = None
    for t in product(range(6), repeat=ell - 1):
        c = (0,) + t
        if sat_geometry(ell, k, c):
            sat += 1
            if first is None:
                first = {"cells": list(c), "palettes": witness(ell, k, c)}
    return total, sat, first


if __name__ == "__main__":
    import json
    out = []
    print(f"{'k':>2} {'ell':>3} {'m':>2} {'geometries':>10} {'SAT':>8}  status")
    for k in (4, 5, 6, 7):
        for ell in range(3, k + 1):
            total, sat, first = scan(ell, k)
            st = "SAT" if sat else "UNSAT (all ray geometries)"
            print(f"{k:>2} {ell:>3} {k-ell:>2} {total:>10} {sat:>8}  {st}", flush=True)
            out.append({"k": k, "ell": ell, "m": k - ell, "positions": NPOS,
                        "geometries": total, "sat": sat, "witness": first})
    json.dump(out, open("interface_csp12_results.json", "w"), indent=1)
