# B.  trigonometric identities behind the k = 5 calibration
# ===========================================================================

def says_B():
    print("\n=== B. the three identities of the k=5 calibration ===")
    import sympy as sp
    phi, d, xi, up = sp.symbols("phi delta xi upsilon", real=True)
    # (B1) sin(3(phi-d)) sin(3(phi+d)) = sin^2(3phi) - sin^2(3d)
    # decided in the exponential ring, which is a complete method for
    # trigonometric identities with linear arguments.
    e1 = sp.sin(3 * (phi - d)) * sp.sin(3 * (phi + d)) \
        - (sp.sin(3 * phi) ** 2 - sp.sin(3 * d) ** 2)
    e1 = sp.expand(sp.expand(e1.rewrite(sp.exp)))
    ok1 = sp.simplify(e1) == 0
    check("B1 sin3(phi-d) sin3(phi+d) = sin^2 3phi - sin^2 3delta", ok1)
    # (B2) sin^2(3phi) = ups^2 (3 xi^2 - ups^2)^2 / l^3 , l = xi^2+ups^2
    l = xi ** 2 + up ** 2
    # sin(3phi) = Im((xi+i ups)^3)/r^3 = (3 xi^2 ups - ups^3)/l^{3/2}
    s3phi = (3 * xi ** 2 * up - up ** 3) / l ** sp.Rational(3, 2)
    e2 = sp.simplify(sp.expand(s3phi ** 2 - up ** 2 * (3 * xi ** 2 - up ** 2) ** 2 / l ** 3))
    check("B2 sin^2 3phi = ups^2 (3xi^2-ups^2)^2 / l^3", e2 == 0)
    # (B3) cos delta = r/2, l = r^2  =>  sin(3 delta) = sqrt(1-l/4) (l-1)
    # decided exactly: with s = sin delta, c = cos delta, c^2 = 1-s^2,
    # triple angle 3s-4s^3 and 4c^2-1 = 3-4s^2 are polynomial identities.
    s = sp.symbols("s", positive=True)
    c2 = 1 - s ** 2
    e3 = sp.expand((3 * s - 4 * s ** 3) - s * (4 * c2 - 1))
    check("B3 sin 3delta = 3s - 4s^3 = s (4cos^2 delta - 1)", e3 == 0)
    # and with s = sqrt(1-l/4):  s*(4c^2-1) = s*(4(1-s^2)-1) = s*(l-1) since
    # 1-s^2 = l/4.  Exact rational identity in l.
    ll = sp.symbols("l", positive=True)
    ss = sp.sqrt(1 - ll / 4)
    e4 = sp.simplify(ss * (4 * (1 - ss ** 2) - 1) - ss * (ll - 1))
    check("B3' = sqrt(1-l/4)(l-1) with l = r^2", e4 == 0)
    return ok1 and e2 == 0 and e3 == 0 and e4 == 0


