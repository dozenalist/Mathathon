"""
SAT test: is the conflict graph of the hexagonal-cell method k-colourable
(on a finite window, and on a torus quotient)?

conflict graph G_d:  vertices = triangular lattice Lambda;
  p ~ q  iff  the cells H_p, H_q contain interior points at distance exactly 1.
Colouring G_d with k colours  <=>  a proper k-colouring of the plane by
nearest-lattice-point cell colouring (Theorem of theorem.md).
"""
import subprocess, sys, os, itertools
from fractions import Fraction as F

def qneg(x): return (-x[0],-x[1])
def q(a,b=0): return (F(a),F(b))
def qadd(x,y): return (x[0]+y[0],x[1]+y[1])
def qsub(x,y): return (x[0]-y[0],x[1]-y[1])
def qmul(x,y): return (x[0]*y[0]+3*x[1]*y[1], x[0]*y[1]+x[1]*y[0])
def qscale(x,t):
    t=F(t); return (x[0]*t,x[1]*t)
def qinv(x):
    a,b=x; d=a*a-3*b*b; return (a/d,-b/d)
def qsign(x):
    a,b=x
    if a==0 and b==0: return 0
    if a>=0 and b>=0: return 1
    if a<=0 and b<=0: return -1
    dd=a*a-3*b*b
    if a>0: return 1 if dd>0 else -1
    return -1 if dd>0 else 1
def qlt(x,y): return qsign(qsub(x,y))<0
def qle(x,y): return qsign(qsub(x,y))<=0
def qmin(*xs):
    m=xs[0]
    for x in xs[1:]:
        if qlt(x,m): m=x
    return m
ONE=q(1); ZERO=q(0); S3=q(0,1)
def lat(i,j): return (q(F(i)-F(j,2)), q(0,F(j,2)))
def vsub(u,v): return (qsub(u[0],v[0]),qsub(u[1],v[1]))
def dot(u,v): return qadd(qmul(u[0],v[0]),qmul(u[1],v[1]))
def n2(u): return dot(u,u)
def qabs(x): return x if qsign(x)>=0 else qneg(x)
r3=qscale(S3,F(1,3))
HVERT=[(q(F(1,2)),qscale(S3,F(1,6))),(q(0),qscale(S3,F(1,3))),(q(F(-1,2)),qscale(S3,F(1,6)))]
HVERT=HVERT+[(qneg(v[0]),qneg(v[1])) for v in HVERT]
U=[(q(1),q(0)),(q(F(-1,2)),q(0,F(1,2))),(q(F(1,2)),q(0,F(1,2)))]
SV=[(qmul(v[0],q(2)),qmul(v[1],q(2))) for v in HVERT]
def in2H(v): return all(qle(qabs(dot(v,u)),ONE) for u in U)
def d2seg(v,a,b):
    d=vsub(b,a); w=vsub(v,a); dd=dot(d,d)
    t=(q(0) if qsign(dd)==0 else qmul(dot(w,d),qinv(dd)))
    if qsign(t)<0: t=ZERO
    if qlt(ONE,t): t=ONE
    p=(qadd(a[0],qmul(t,d[0])),qadd(a[1],qmul(t,d[1])))
    return n2(vsub(v,p))
def delta_min2(v):
    if in2H(v): return ZERO
    W=SV+[SV[0]]
    return qmin(*[d2seg(v,W[i],W[i+1]) for i in range(len(SV))])
def delta_max2(v):
    m=n2(vsub(v,SV[0]))
    for w in SV[1:]:
        t=n2(vsub(v,w))
        if qlt(m,t): m=t
    return m
def conflict(d2,v):
    dm2=delta_min2(v)
    if not qlt(qscale(dm2,d2),ONE): return False
    return qlt(ONE,qscale(delta_max2(v),d2))

# ---------- conflict shell list for given d (lattice vectors, exact)
def shells(d2, nmax2=200):
    out=[]
    R=0
    while True:
        R+=1
        if R>nmax2: break
    for a in range(-20,21):
        for b in range(-20,21):
            if (a,b)==(0,0): continue
            nn=a*a-a*b+b*b
            if nn>nmax2: continue
            if conflict(d2, lat(a,b)): out.append((a,b,nn))
    return out

# ---------- CNF build
def build_cnf(vertices, edges, k):
    idx={v:i*k for i,v in enumerate(vertices)}     # variable (v,c) = idx[v]+c+1
    nv=len(vertices)*k
    clauses=[]
    for v in vertices:
        clauses.append([idx[v]+c+1 for c in range(k)])
    for (u,w) in edges:
        for c in range(k):
            clauses.append([-(idx[u]+c+1), -(idx[w]+c+1)])
    return nv, clauses

def run_cadical(nv, clauses, tl=20):
    lines=[f"p cnf {nv} {len(clauses)}"]
    for cl in clauses: lines.append(" ".join(map(str,cl))+" 0")
    path=".scratch_cnf.cnf"
    open(path,"w").write("\n".join(lines)+"\n")
    try:
        r=subprocess.run(["cadical","-q",path],capture_output=True,text=True,timeout=tl)
    except subprocess.TimeoutExpired:
        return None, None
    res = "SAT" if "s SATISFIABLE" in r.stdout else ("UNSAT" if "s UNSATISFIABLE" in r.stdout else "?")
    model=None
    for line in r.stdout.splitlines():
        if line.startswith("v"):
            model = list(map(int, line[1:].split()))
    return res, model

def window_graph(d2, K):
    """vertices: all (a,b) with N(a,b) <= K ; edges from conflict shells"""
    verts=[(a,b) for a in range(-40,41) for b in range(-40,41) if a*a-a*b+b*b<=K]
    sh=shells(d2)
    vs=set(verts); edges=set()
    for v in verts:
        for (a,b,nn) in sh:
            w=(v[0]+a,v[1]+b)
            if w in vs:
                e=tuple(sorted([v,w]))
                edges.add(e)
    return verts, sorted(edges)

def torus_graph(d2, kernel):
    """period lattice generated by 'kernel' (list of integer vectors); vertices = cosets"""
    sh=shells(d2)
    # enumerating the quotient: use HNF of the period lattice
    import itertools
    # brute force: find representable complete residue system by BFS over Z^2
    reps={}
    from collections import deque
    start=(0,0)
    reps[start]=0; order=[start]; dq=deque([start])
    while dq:
        v=dq.popleft()
        for w in kernel:
            for s in (1,-1):
                u=(v[0]+s*w[0], v[1]+s*w[1])
                if u not in reps:
                    reps[u]=len(order); order.append(u); dq.append(u)
                elif reps[u]!=reps[v]:
                    pass
    return None

