# C.  the k = 5 calibration: (8.4)  <=>  both outsiders excluded
# ===========================================================================

def moser_points():
    """the seven placed Moser vertices z_g of the paper, (8.5)-(8.6), as exact
    elements of Q(sqrt3, sqrt11, i): return (xi, ups) pairs.

    NOTE the parenthesisation: the paper's displayed (8.6) reads
    z_g = ((35+12i)/37) g + (-290+149i)/250, but its own Table 1 corresponds to
    z_g = ((35+12i)/37) (g + (-290+149i)/250).  The two differ by translating
    before rather than after the rotation; only the second satisfies (8.4) at
    g = 0 (checked in block C6).  Block C uses the placement that matches the
    paper's table, i.e. the one its certificate actually verifies."""
    A = (Alg(0, F(1, 2)), Alg(F(1, 2), 0, 0, 0))      # sqrt3/2 + i/2
    B = (Alg(0, F(1, 2)), Alg(-F(1, 2), 0, 0, 0))
    T = (Alg(0, 1), Alg(0))                           # sqrt3
    u = (Alg(F(5, 6)), Alg(0, 0, F(1, 6), 0))         # 5/6 + i sqrt11/6

    def cmul(p, q):
        return (p[0] * q[0] - p[1] * q[1], p[0] * q[1] + p[1] * q[0])

    uA = cmul(u, A)
    uB = cmul(u, B)
    uT = cmul(u, T)
    G = {"0": (Alg(0), Alg(0)), "A": A, "B": B, "T": T,
         "uA": uA, "uB": uB, "uT": uT}
    lam = (Alg(F(35, 37)), Alg(F(12, 37)))
    tau = (Alg(F(-290, 250)), Alg(F(149, 250)))
    out = {}
    for k, g in G.items():
        out[k] = cmul(lam, (g[0] + tau[0], g[1] + tau[1]))
    return out, G, lam, tau


def says_C():
    print("\n=== C. k=5 calibration: (8.4) <=> both outsiders excluded ===")
    zs, G, lam, tau = moser_points()
    # check the multiplier has norm one: 35^2+12^2 = 37^2
    check("C0 |(35+12i)/37| = 1 (35^2+12^2 = 37^2)", 35 * 35 + 12 * 12 == 37 * 37)
    # C0b the eleven drawn unit edges of the Moser graph (8.5), exactly:
    # two equilateral triangles 0AB and TAB sharing AB, their rotated copies
    # 0,uA,uB and uT,uA,uB (u has |u| = 1), and the contradiction edge T,uT.
    edges = [("0", "A"), ("0", "B"), ("A", "B"), ("T", "A"), ("T", "B"),
             ("0", "uA"), ("0", "uB"), ("uA", "uB"),
             ("uT", "uA"), ("uT", "uB"), ("T", "uT")]
    eok = True
    for p, q in edges:
        gp, gq = G[p], G[q]
        dd = (gp[0] - gq[0], gp[1] - gq[1])
        d2 = dd[0] * dd[0] + dd[1] * dd[1]
        eok &= (sign_proc2(d2 - Alg(1)) == 0 and iv(d2 - Alg(1)).contains_zero())
    check("C0b all eleven drawn Moser edges have length exactly one", eok)
    # C0c the forced-equality edge: |T - uT| = 1 (the contradiction)
    dd = (G["T"][0] - G["uT"][0], G["T"][1] - G["uT"][1])
    d2 = dd[0] * dd[0] + dd[1] * dd[1]
    check("C0c |T - uT| = 1 exactly (the Moser contradiction edge)",
          sign_proc2(d2 - Alg(1)) == 0)
    allok = True
    for name, (xi, up) in zs.items():
        l = xi * xi + up * up                      # |z|^2  in Alg
        # 0 < l < 4
        s_l = sign_proc2(l)
        s_l4 = sign_proc2(4 - l)
        iv_l, iv_l4 = iv(l), iv(4 - l)
        ok_l = (s_l == 1 and s_l4 == 1 and iv_l.sign() == 1 and iv_l4.sign() == 1)
        allok &= check("C1.%s  0 < |z_g|^2 = l < 4  (both procedures)" % name, ok_l)
        # P = ups^2 (3xi^2 - ups^2)^2 ;  Pp = l^3 (1-l/4)(l-1)^2
        t1 = 3 * xi * xi - up * up
        P = up * up * t1 * t1
        four = Alg(4)
        Pp = l * l * l * (Alg(1) - l / four) * (l - Alg(1)) * (l - Alg(1))
        diff = Pp - P
        s1 = sign_proc2(diff)
        s2 = iv(diff).sign()
        okP = (s1 == 1 and s2 == 1)
        allok &= check("C2.%s  P < P'  (the paper's (8.4); both procedures)" % name, okP,
                       "PROC-2 %+d  PROC-1 %+d" % (s1, s2))
    # C6 the erratum: with the *literal* parenthesisation of (8.6) the vertex
    # g = 0 fails (8.4), so the displayed formula does not verify its own table.
    z0 = (Alg(F(-290, 250)), Alg(F(149, 250)))
    xi, up = z0
    l = xi * xi + up * up
    t1 = 3 * xi * xi - up * up
    P = up * up * t1 * t1
    four = Alg(4)
    Pp = l * l * l * (Alg(1) - l / four) * (l - Alg(1)) * (l - Alg(1))
    check("C6 literal (8.6) at g=0: P > P' (inner point), so (8.4) FAILS "
          "(parenthesisation erratum)",
          sign_proc2(Pp - P) == -1 and iv(Pp - P).sign() == -1)
    return allok


