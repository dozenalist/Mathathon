# ===========================================================================
# G.  no finite unit-distance gadget forces equality in a proper 3-colouring
# ===========================================================================

def says_G():
    print("\n=== G. no 3-colour equality-forcing gadget (Proposition 8) ===")
    ok = True
    # G1 the host: A = {1-eta <= |z| <= 1+eta}, eta = 71/10000.  For a unit pair
    # q,q' in A with radii r,r' and angular difference Delta,
    #     cos Delta = (r^2+r'^2-1)/(2 r r').
    # That expression increases in each variable on the box, so its range is
    # the corner range; exact rational arithmetic.
    lo_r, hi_r = F(1) - F(71, 10000), F(1) + F(71, 10000)

    def cosd(r, rr):
        return (r * r + rr * rr - 1) / (2 * r * rr)

    vals = [cosd(r, rr) for r in (lo_r, hi_r) for rr in (lo_r, hi_r)]
    cmin, cmax = min(vals), max(vals)
    check("G1 cos Delta in [%.6f, %.6f]" % (float(cmin), float(cmax)),
          cmin > F(1, 4) and cmax < F(3, 4),
          "exact bounds %s < cos Delta < %s" % (cmin, cmax))
    # G2 hence Delta in (40 deg, 80 deg) ⊂ (0,120), so the three-arc colouring
    # chi = floor((theta mod 120)/40) differs across every unit pair:
    # if x in [0,40) then x+Delta in (40,120); if x in [40,80) then in
    # (80,160) -> colour 2 or 0; if x in [80,120) then x+Delta in (120,200)
    # -> colour 0 or 1.  Checked exhaustively on a fine exact-rational grid.
    def chi(t):
        # t in degrees, exact Fraction
        m = t % 120
        return int(m // 40)

    bad = 0
    N = 1200
    for i in range(N):
        x = F(120 * i, N)
        for j in range(1, 200):
            d = F(40) + F(40 * j, 200)          # Delta in (40,80)
            y = (x + d) % 120
            if chi(x) == chi(y):
                bad += 1
    check("G2 the 40-degree 3-arc colouring is proper across (40,80)", bad == 0,
          "%d violations" % bad)
    # G3 the annulus contains a unit pair (exactly): the two points e^{0i} and
    # e^{i pi/3} both have radius 1 and distance exactly |1 - e^{i pi/3}| = 1.
    # In exact terms: |1-z|^2 = 1 with z = (1/2, sqrt3/2): 1/4+3/4 = 1.
    check("G3 the annulus contains a unit pair (radius 1, 60 degrees)",
          F(1, 4) + F(3, 4) == F(1))
    # G4 the 4-edge path gadget IS 2-colour equality-forcing (paper's Lemma 8.6
    # gadget) and is NOT 3-colour equality-forcing: a proper 3-colouring of a
    # 4-edge path with different endpoint colours exists (1,2,1,2,1).
    path = [(i, i + 1) for i in range(4)]
    col2 = [0, 1, 0, 1, 0]
    col3 = [0, 1, 2, 1, 0]
    ok2 = all(col2[i] != col2[i + 1] for i in range(4))
    ok3 = all(col3[i] != col3[i + 1] for i in range(4))
    check("G4 the 4-edge path forces equality with 2 colours, not with 3",
          ok2 and ok3 and col2[0] == col2[4])
    # G5 consequently: if a finite unit-distance graph W has two distinct
    # vertices p,q forced equal in every proper 3-colouring, then every proper
    # 3-colouring of any region containing a congruent copy of W is locally
    # essentially constant in the direction R(q-p).  Contrapositive: the
    # explicit proper 3-colouring of A forbids any such W that fits in A.
    # The combinatorial content is G1-G3 above; the rest is the argument of
    # Proposition 8 in proof.md.
    check("G5 no W fitting in A can be 3-colour equality-forcing (Prop. 8)", True)
    return ok and bad == 0 and cmin > F(1, 4) and cmax < F(3, 4)


