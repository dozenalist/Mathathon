def sat_window(d2, K, k=6, tl=30, verbose=True):
    verts, edges = window_graph(d2, K)
    nv, clauses = build_cnf(verts, edges, k)
    res, model = run_cadical(nv, clauses, tl=tl)
    if verbose:
        print(f"    window norm^2<={K}: |V|={len(verts)} |E|={len(edges)} vars={nv} "
              f"clauses={len(clauses)} -> {res}")
    return res, verts, model

