"""cellbar.py -- exact analysis of cell-constant colourings of lattice tilings of the plane.

The question (mission D13, chi <= 6 side): the only known route to an upper bound chi(R^2) <= k
is a colouring that is CONSTANT ON THE CELLS of a lattice tiling and proper on the
"reachability" relation: two cells must get different colours whenever they can contain two
points at distance exactly 1.  This script settles, exactly, for the hexagonal (triangular
lattice) family -- the family that produces the best known bound 7 -- the chromatic number of
that reachability graph as a function of the circumradius r of the cells.

Everything is exact: all coordinates lie in Q(sqrt 3) (see q3.py) and every comparison is a
rational comparison.

Run:  python3 cellbar.py
"""
from fractions import Fraction as F
import json
from q3 import Q3, Pt, q3, SQ3, ZERO, ONE, HALF, hexagon, poly_dist2, lattice_pt

OUT = {}
Q = lambda *a: Q3(*a)


# --------------------------------------------------------------- reachability
def reachable(v, r):
    """Exact test: can the two hexagonal cells C and C+v of circumradius r contain a pair of
    points at distance exactly 1?

    C is centrally symmetric, so C - C = 2C, and the set of distances realized by a pair
    (x,y) in C x (C+v) is { |v + w| : w in 2C } = 2 * { |v/2 + c| : c in C }.
    Hence 1 is realized iff  dist(v/2, C) <= 1/2  and  max_{c in C} |v/2 + c| >= 1/2.
    For the regular hexagon of circumradius r, max_{c in C} |a + c| = |a| + r, so the second
    condition is |v|/2 + r >= 1/2, i.e. |v| >= 1 - 2r.
    """
    H = hexagon(r)
    if poly_dist2(v * HALF, H) > Q(F(1, 4)):
        return False
    if r <= HALF:
        return v.norm2() >= (ONE - Q3(2) * r) * (ONE - Q3(2) * r)
    return True


def offsets_within(r, R):
    """All lattice offsets v = L(i + j omega) with |v| <= R, as (i, j, Pt).  Finite enumeration:
    |v|^2 = 3 r^2 (i^2 - i j + j^2), so Q(i,j) = i^2 - i j + j^2 <= R^2/(3 r^2)."""
    R = q3(R)
    lim = (R * R) / (Q3(3) * q3(r) * q3(r))            # upper bound on Q(i,j) = i^2 - i j + j^2
    limf = lim.float()
    N = int(limf ** 0.5) + 3
    out = []
    for i in range(-N, N + 1):
        for j in range(-N, N + 1):
            v = lattice_pt(i, j, r)
            if v.norm2() <= R * R:
                out.append((i, j, v))
    return out


# ------------------------------------------------------------------ the seven
def sub_2mw(i, j):
    """Multiplication by (2 - omega) on Z[omega]:  (i + j omega) -> (2i+j) + (3j-i) omega."""
    return (2 * i + j, 3 * j - i)


def colour7(i, j):
    """The index-seven coset label used by Hadwiger's construction; it vanishes on (2-omega)Z[omega]."""
    return (i + 2 * j) % 7


def seven_colouring_proper(r):
    """Exact check: are any two distinct same-colour cells reachable?  Returns (ok, worst)."""
    cand = offsets_within(r, ONE + Q3(2) * q3(r))       # reachability needs |v| <= 1 + 2r
    bad = []
    for (i, j, v) in cand:
        if (i, j) == (0, 0):
            continue
        if colour7(i, j) == 0 and reachable(v, r):
            bad.append((i, j, v))
    return (len(bad) == 0), bad


# ------------------------------------------------------------- sublattice norms
def form(i, j):
    return i * i - i * j + j * j


def max_min_norm_by_index(NMAX):
    """m(n) = max over sublattices L' of Z^2 of index n of min{ form(v) : 0 != v in L' }.
    (The hexagonal lattice L*Z[omega] scaled by L has |v|^2 = 3 r^2 form(i,j), so min norm
    form = t means min length = L sqrt(t).)  Sublattices of index n are the Hermite normal
    form matrices [[a,b],[0,d]] with a*d = n, 0 <= b < d."""
    best = {}
    arg = {}
    n = 1
    while n <= NMAX:
        a = 1
        while a <= n:
            if n % a == 0:
                d = n // a
                for b in range(d):
                    # sublattice generated by (a, b) and (0, d)
                    gen = [(a, b), (0, d)]
                    K = int((4 * n) ** 0.5) + 4
                    mn = None
                    for s in range(-K, K + 1):
                        for t in range(-K, K + 1):
                            if s == 0 and t == 0:
                                continue
                            x = s * gen[0][0] + t * gen[1][0]
                            y = s * gen[0][1] + t * gen[1][1]
                            q = form(x, y)
                            if mn is None or q < mn:
                                mn = q
                    if mn is None:
                        continue
                    if n not in best or mn > best[n]:
                        best[n] = mn
                        arg[n] = (a, b, d)
            a += 1
        n += 1
    return best, arg


# -------------------------------------------------------------------- K7 hunt
def find_clique(r, size, cand):
    """Greedy/backtracking search for a clique of `size` in the reachability graph."""
    adj = {}
    pts = [v for (_, _, v) in cand]
    idx = {v: k for k, v in enumerate(pts)}
    n = len(pts)
    nb = [[False] * n for _ in range(n)]
    for p in range(n):
        for q in range(p + 1, n):
            if reachable(pts[q] - pts[p], r):
                nb[p][q] = nb[q][p] = True
    best = []

    def ext(cur, allowed):
        nonlocal best
        if len(cur) + len(allowed) <= len(best):
            return
        if len(cur) >= size:
            best = cur[:]
            return
        if not allowed:
            return
        for pos, w in enumerate(allowed):
            ext(cur + [w], [u for u in allowed[pos + 1:] if nb[w][u]])
            if len(best) >= size:
                return

    ext([], list(range(n)))
    return [pts[k] for k in best] if len(best) >= size else []


def main():
    from math import sqrt
    r0 = 1 / (sqrt(21) - 2)                 # upper limit of validity of the 7-coset colouring
    crit = 2 - sqrt(3)                      # lower limit of validity of the 7-clique
    OUT["r0_exact"] = "1/(sqrt21-2)"
    OUT["r0"] = r0
    OUT["7clique_threshold"] = "2 - sqrt3"
    OUT["2-sqrt3"] = crit

    # 1. sanity check of the abstract criterion against brute force in the continuum
    sanity = []
    for r in [F(2, 5), F(1, 3), F(1, 4)]:
        H = hexagon(r)
        for (i, j) in [(1, 0), (0, 1), (1, 1), (2, 0), (2, 1), (3, 1), (0, 2), (4, 2), (5, 1)]:
            v = lattice_pt(i, j, r)
            # brute force: min/max of |v/2 + c| over c in C, by dense sampling
            lo, hi = None, None
            for k in range(6):
                for t in [x / 60 for x in range(61)]:
                    a, b = H[k], H[(k + 1) % 6]
                    c = a * (1 - t) + b * t
                    p = v * HALF + c
                    d = p.norm2().float() ** 0.5
                    lo = d if lo is None else min(lo, d)
                    hi = d if hi is None else max(hi, d)
            brute = (lo <= 0.5 + 1e-9) and (hi >= 0.5 - 1e-9)
            ex = reachable(v, r)
            sanity.append({"r": str(r), "v": (i, j), "brute": bool(brute), "exact": bool(ex)})
    OUT["criterion_sanity"] = sanity
    OUT["criterion_sanity_all_agree"] = all(s["brute"] == s["exact"] for s in sanity)

    # 2. the seven-colouring: exact properness as a function of r
    tab = []
    for rnum in [F(1, 3), F(19, 50), F(388, 1000), F(2, 5), F(9, 20), F(49, 100)]:
        ok, bad = seven_colouring_proper(rnum)
        tab.append({"r": str(rnum), "r_float": float(rnum), "proper": ok, "violations": len(bad)})
    OUT["seven_colouring"] = tab
    OUT["seven_colouring_min_r"] = r0

    # 3. the 7-clique on the hexagonal family: explicit certificate at r = 2/5 and near limits
    cl = []
    for rnum in [F(2, 5), F(9, 20), F(49, 100), F(3, 10)]:
        cand = offsets_within(rnum, ONE + Q3(2) * q3(rnum))
        pts = find_clique(rnum, 7, cand)
        cl.append({"r": str(rnum), "r_float": float(rnum), "clique7": len(pts) == 7,
                   "points_float": [p.float() for p in pts]})
    OUT["clique7"] = cl

    # 4. below 2 - sqrt3: does a 7-clique still exist?  (the 7-cell hexagon is no longer a clique)
    low = []
    for rnum in [F(1, 4), F(1, 5), F(1, 6), F(1, 8), F(1, 10), F(1, 20)]:
        cand = offsets_within(rnum, ONE + Q3(2) * q3(rnum))
        pts = find_clique(rnum, 7, cand)
        low.append({"r": str(rnum), "r_float": float(rnum), "n_offsets": len(cand),
                    "clique7": len(pts) == 7, "points_float": [p.float() for p in pts]})
    OUT["clique7_small_r"] = low

    # 5. sublattice index table: how many colours does a COSET colouring need at each r?
    m, arg = max_min_norm_by_index(40)
    OUT["max_min_form_by_index"] = {str(k): m[k] for k in sorted(m)}
    OUT["argmin_sublattice"] = {str(k): arg[k] for k in sorted(arg)}
    need = []
    for rnum in [F(2, 5), F(19, 50), F(388, 1000), F(38, 100), F(3, 10), F(1, 4),
                 F(1, 5), F(1, 8), F(1, 10), F(1, 20)]:
        r = q3(rnum)
        target = (ONE + Q3(2) * r) * (ONE + Q3(2) * r) / (Q3(3) * r * r)   # need min form > this
        tf = target.float() if hasattr(target, "float") else float(target)
        n = None
        for k in sorted(m):
            if m[k] > tf:
                n = k
                break
        need.append({"r": str(rnum), "r_float": float(rnum), "target_form": tf,
                     "min_index_for_coset_colouring": n})
    OUT["coset_index_needed"] = need

    with open("cellbar_results.json", "w") as f:
        json.dump(OUT, f, indent=1)
    for k, v in OUT.items():
        if k in ("criterion_sanity",):
            print(k, ":", "all agree" if OUT["criterion_sanity_all_agree"] else "MISMATCH")
            continue
        print(k, ":", json.dumps(v)[:600])


if __name__ == "__main__":
    main()
