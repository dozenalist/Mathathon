"""Emit DATA.md: raw family tables.  No analysis, just exact integers.

Run:  python3 make_data.py > DATA.md
"""
import sys
import os
def _computation_dir():
    here = os.path.dirname(os.path.abspath(__file__))
    cands = [os.path.join(here, "..", "..", "Computation"),
             os.path.join(here, "..", "..", "..", "repo", "RogersRamanujan", "Computation"),
             "/workspace/nucleus/work/projects/p-9021becf3f0d47a89b3f3c794c1e872b/repo/RogersRamanujan/Computation",
             os.environ.get("RR_COMPUTATION", "")]
    for c in cands:
        if c and os.path.isfile(os.path.join(c, "bz82.py")):
            return os.path.abspath(c)
    raise SystemExit("cannot locate RogersRamanujan/Computation/bz82.py")
BASE = _computation_dir()
sys.path.insert(0, BASE)
from rr_core import enumerate_residue, weight
from bz82 import pi_forward

def dshow(p): return "(" + ",".join(map(str,p)) + ")" if p else "()"
def inB(p):
    k=len(p); return all(x>=k for x in p)

print("# Raw family data (generated by `python3 make_data.py`)")
print()
print("`b` is the B-endpoint produced by `Computation.bz82.pi_forward`, `lam` the")
print("D-image `Tinv(b)`, `steps` the number of alternating applications.")
print("Columns are defined by the printed rules only; see PROOF_families.md.")
print()
print("## F1  the all-ones ray (1^s)")
print()
print("| s | b | lam | steps | b in B | lam in D |")
print("|---|---|---|---|---|---|")
for s in range(0, 61):
    b, tr = pi_forward((1,)*s)
    lam = tuple(b[i] + len(b) - 2*(i+1) + 1 for i in range(len(b)))
    okB = all(x >= len(b) for x in b)
    okD = all(lam[i] >= lam[i+1] + 2 for i in range(len(lam)-1))
    print("| %d | %s | %s | %d | %s | %s |" % (s, dshow(b), dshow(lam), len(tr)-1, okB, okD))
print()
print("## F2  the all-fours ray (4^r)")
print()
print("| r | n | b | lam | steps |")
print("|---|---|---|---|---|")
for r in range(0, 21):
    b, tr = pi_forward((4,)*r)
    lam = tuple(b[i] + len(b) - 2*(i+1) + 1 for i in range(len(b)))
    print("| %d | %d | %s | %s | %d |" % (r, 4*r, dshow(b), dshow(lam), len(tr)-1))
print()
print("## F3  two-parameter grid (4^r,1^s): B-endpoint only")
print()
print("Rows r = 0..8, columns s = 0..12.  The entry is `b`; `*` marks a")
print("single-part endpoint, `+` a two-part endpoint.")
print()
hdr = "| r\\s | " + " | ".join(str(s) for s in range(0,13)) + " |"
print(hdr)
print("|" + "---|"*(14))
for r in range(0, 9):
    row = []
    for s in range(0, 13):
        if r + s == 0:
            row.append("()"); continue
        b, tr = pi_forward((4,)*r + (1,)*s)
        mark = "*" if len(b) == 1 else ("+" if len(b) == 2 else " ")
        row.append(mark + dshow(b).replace("(", "").replace(")", ""))
    print("| %d | %s |" % (r, " | ".join(row)))
print()
print("## F4  free window: A_n cap B_n, and path-length counts")
print()
print("| n | \\|A_n\\| | \\|A_n cap B_n\\| | max steps | mean steps | #(steps<=2) | #(steps<=6) |")
print("|---|---|---|---|---|---|---|")
tf = [0,0]
for n in range(0, 41):
    A = enumerate_residue(n)
    w = [a for a in A if inB(a)]
    st = [len(pi_forward(a)[1])-1 for a in A]
    tf[0] += len(w); tf[1] += len(A)
    print("| %d | %d | %d | %d | %.3f | %d | %d |" % (n, len(A), len(w),
          max(st) if st else 0, (sum(st)/len(st)) if st else 0,
          sum(1 for x in st if x <= 2), sum(1 for x in st if x <= 6)))
print()
print("Free-window fraction over n <= 40: %d/%d = %.4f." % (tf[0], tf[1], tf[0]/tf[1]))
