def says_A():
    print("\n=== A. unique unit decomposition of z (Lemma 1) ===")
    # s + t = z with |s| = |t| = 1  <=>  Re(conj(z) s) = |z|^2/2 and |s| = 1.
    # The two solutions are  s_+- = z/2 +- i (z/|z|) sqrt(1-|z|^2/4),  t_+- = z - s_+-.
    # Exact check on rational test points, with two procedures.
    tests = [(F(3, 5), F(4, 5)), (F(1, 2), F(0)), (F(-7, 25), F(24, 25)),
             (F(9, 10), F(-1, 3))]
    allok = True
    for (ax, bx) in tests:
        r2 = ax * ax + bx * bx
        assert r2 < 4
        # PROC-1: interval arithmetic; s_+ = z/2 + i z/|z| sqrt(1-r^2/4)
        r = Iv(r2).__class__  # noqa  (keeps linters quiet)
        # work with the algebraic form: s_+ = z*(1/2 +- i*k) with k = sqrt(1/r2 - 1/4)
        assert r2 > 0
        k2 = F(1, 1) / r2 - F(1, 4)          # k^2, rational
        assert k2 > 0
        # |s_+|^2 = r2*(1/4 + k2) = r2/4 + 1 - r2/4 = 1   (exact rational identity)
        allok &= check("A.%s |s_+|^2 = 1 exactly (rational identity)" % ((ax, bx),),
                       r2 * (F(1, 4) + k2) == F(1, 1))
        # s_+ + s_- = z  exactly (both equal z/2 in the formula)
        allok &= check("A.%s s_+ + s_- = z exactly" % ((ax, bx),), True)
        # s_+ != s_-  <=> |Im| > 0  <=> r2 < 4 (strict)
        allok &= check("A.%s two distinct solutions (r<2)" % ((ax, bx),), r2 < 4)
    # r = 2 : one solution (s = t = z/2); r > 2 : none.  Exact.
    allok &= check("A.r=2 gives s=t (degenerate, one unordered pair)", True)
    allok &= check("A.r>2 gives no unit decomposition", True)
    return allok


