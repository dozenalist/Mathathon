"""Exact arithmetic in K = Q(sqrt3, sqrt11) and K[i] = K + iK.
Elements of K are 4-tuples (q0,q1,q2,q3) of Fractions meaning q0 + q1*sqrt3 + q2*sqrt11 + q3*sqrt33.
Elements of K[i] are pairs (re, im) of K-elements.
All operations exact.
"""
from fractions import Fraction as F

ZERO = (F(0),)*4
ONE  = (F(1),F(0),F(0),F(0))

def Kadd(x,y): return tuple(a+b for a,b in zip(x,y))
def Ksub(x,y): return tuple(a-b for a,b in zip(x,y))
def Kneg(x): return tuple(-a for a in x)
def Kscale(x,s): return tuple(a*s for a in x)
def Kmul(x,y):
    x0,x1,x2,x3 = x; y0,y1,y2,y3 = y
    # basis 1, s3, s11, s33 ; s3*s3=3, s11*s11=11, s3*s11=s33, s3*s33=3*s11, s11*s33=11*s3, s33*s33=33
    r0 = x0*y0 + 3*x1*y1 + 11*x2*y2 + 33*x3*y3
    r1 = x0*y1 + x1*y0 + 11*x2*y3 + 11*x3*y2
    r2 = x0*y2 + x2*y0 + 3*x1*y3 + 3*x3*y1
    r3 = x0*y3 + x3*y0 + x1*y2 + x2*y1
    return (r0,r1,r2,r3)
def Kzero(x): return all(a==0 for a in x)

def add(z,w): return (Kadd(z[0],w[0]), Kadd(z[1],w[1]))
def sub(z,w): return (Ksub(z[0],w[0]), Ksub(z[1],w[1]))
def mul(z,w):
    a,b = z; c,d = w
    return (Ksub(Kmul(a,c), Kmul(b,d)), Kadd(Kmul(a,d), Kmul(b,c)))
def conj(z): return (z[0], Kneg(z[1]))
def Kaut(x):
    """field automorphism sqrt3 -> -sqrt3, sqrt11 -> sqrt11, sqrt33 -> -sqrt33"""
    return (x[0], -x[1], x[2], -x[3])
def norm2(z):  # |z|^2 in K
    return Kadd(Kmul(z[0],z[0]), Kmul(z[1],z[1]))
def is_unit(z): return Kzero(Ksub(norm2(z), ONE))
def is_zero(z): return Kzero(z[0]) and Kzero(z[1])

# rotation by pi/3 : multiply by (1/2 + i sqrt3/2)
ROT = ((F(1,2),F(0),F(0),F(0)), (F(0),F(1,2),F(0),F(0)))
def rot(z): return mul(ROT,z)
def reflect_x(z): return (z[0], Kneg(z[1]))
def conjfield(z): return (Kaut(z[0]), Kaut(z[1]))   # Parts' b,c sign flip

def from_ints(a,b,c,d,den=12):
    return ((F(a,den),F(b,den),F(0),F(0)), (F(0),F(0),F(c,den),F(d,den)))

def orbit(z):
    """orbit under group generated by rot(pi/3), reflect_x, field conjugation."""
    seen=set(); out=[]
    def key(w):
        return tuple(w[0])+tuple(w[1])
    stack=[z]
    while stack:
        w=stack.pop()
        k=key(w)
        if k in seen: continue
        seen.add(k); out.append(w)
        stack += [rot(w), reflect_x(w), conjfield(w)]
    return out
