def says_E():
    print("\n=== E. R-orbit words at k=6, triangle centres (S_1) ===")
    # beta: Z/6 -> {0,1,2} with beta(j+1) != beta(j) cyclically (5.7)
    words = []
    for w in itertools.product(range(3), repeat=6):
        if all(w[j] != w[(j + 1) % 6] for j in range(6)):
            words.append(w)
    check("E1 number of R-alternating 3-valued orbit words = 66", len(words) == 66,
          "got %d" % len(words))
    three = [w for w in words if len(set(w)) == 3]
    two = [w for w in words if len(set(w)) == 2]
    check("E2 words attaining all three outsider values: 60", len(three) == 60,
          "got %d" % len(three))
    check("E3 2-valued words: 6 (3 pairs x 2 phases)", len(two) == 6, "got %d" % len(two))
    # measure bound m11: sigma{T subset P} <= 1/2.  For a singleton field this
    # says each value occupies at most half the circle; a 3-valued word can
    # satisfy it (equal thirds), so no obstruction.
    ok = True
    for w in three[:1]:
        cnt = {v: sum(1 for x in w if x == v) for v in range(3)}
        ok &= check("E4 equal-thirds word satisfies the bound 1/2 per value",
                    max(cnt.values()) <= 3)
    # 2-valued words are exactly the binary ones: their value set is a pair,
