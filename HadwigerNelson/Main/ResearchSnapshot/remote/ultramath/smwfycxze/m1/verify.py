# exact algebraic numbers  a + b*sqrt3 + c*sqrt11 + d*sqrt33   (a,b,c,d in Q)
# ---------------------------------------------------------------------------

class Alg(object):
    """a + b*sqrt(3) + c*sqrt(11) + d*sqrt(33), coefficients exact Fractions."""
    __slots__ = ("c",)

    def __init__(self, a=0, b=0, c=0, d=0):
        self.c = (F(a), F(b), F(c), F(d))

    def __add__(self, o):
        o = alg(o)
        return Alg(*[x + y for x, y in zip(self.c, o.c)])

    def __radd__(self, o):
        return alg(o) + self

    def __neg__(self):
        return Alg(*[-x for x in self.c])

    def __sub__(self, o):
        return self + (-alg(o))

    def __rsub__(self, o):
        return alg(o) - self

    def __mul__(self, o):
        o = alg(o)
        a, b, c, d = self.c
        e, f, g, h = o.c
        # basis products: 1*1=1 ; 3*3=3 ; 11*11=11 ; 33*33=33 ;
        # 3*11 = 33 ; 3*33 = 3*11 ; 11*33 = 11*3 ; (sqrt3)(sqrt33)=3 sqrt11 etc.
        r0 = a * e + 3 * b * f + 11 * c * g + 33 * d * h
        r1 = a * f + b * e + 3 * d * g + 11 * c * h
        r2 = a * g + c * e + 11 * d * f + 3 * b * h
        r3 = a * h + d * e + b * g + c * f
        return Alg(r0, r1, r2, r3)

    def __rmul__(self, o):
        return alg(o) * self

    def __truediv__(self, o):
        return self * alg(o).inverse()

    def inverse(self):
        # multiply by the three conjugate-field embeddings' product
        conj = [Alg(self.c[0], -self.c[1], self.c[2], -self.c[3]),
                Alg(self.c[0], self.c[1], -self.c[2], -self.c[3]),
                Alg(self.c[0], -self.c[1], -self.c[2], self.c[3])]
        num = Alg(1)
        for k in conj:
            num = num * k
        den = self * num           # rational
        assert den.c[1] == 0 and den.c[2] == 0 and den.c[3] == 0, den.c
        return num * Alg(1 / den.c[0])

    def __repr__(self):
        return "Alg%s" % (self.c,)

    def __eq__(self, o):
        return self.c == alg(o).c

    def __hash__(self):
        return hash(self.c)

    def is_zero(self):
        return all(x == 0 for x in self.c)

    def embeds(self):
        """the four real embeddings (sqrt3 -> +-sqrt3, sqrt11 -> +-sqrt11)"""
        a, b, c, d = self.c

        def val(s3, s11):
            # a + b*s3*sqrt3 + c*s11*sqrt11 + d*s3*s11*sqrt33  -- but sqrt33
            # is sqrt3*sqrt11 only up to sign; the four embeddings of the
            # field generated by sqrt3,sqrt11 are the combinations below.
            # sqrt33 -> s33*sqrt33 with s33 = s3*s11.
            return (a, b * s3, c * s11, d * s3 * s11)
        return [val(1, 1), val(1, -1), val(-1, 1), val(-1, -1)]


def alg(x):
    if isinstance(x, Alg):
        return x
    return Alg(x)


def alg_rational(q):
    """exact Alg for a rational (or int) or a rational combination given as tuple"""
    if isinstance(q, tuple):
        return Alg(*q)
    return Alg(q)


SQ3 = Alg(0, 1, 0, 0)
SQ11 = Alg(0, 0, 1, 0)
SQ33 = Alg(0, 0, 0, 1)


# --- PROC-2 sign decision: nested rational brackets, two bracket families ----

def brackets_sqrt3_iters(n):
    """(lo,hi) rationals with lo^2 < 3 < hi^2, from bisection on the squares.
    Family 1."""
    lo, hi = F(1), F(2)
    for _ in range(n):
        mid = (lo + hi) / 2
        if mid * mid < 3:
            lo = mid
        else:
            hi = mid
    return lo, hi


def brackets_sqrt11_cf(n):
    """Family 2: convergents of the continued fraction of sqrt 11 = [3;3,6,3,6,...]"""
    from fractions import Fraction
    # convergents
    a = [3] + [3, 6] * (n // 2 + 2)
    p0, q0 = F(1), F(0)
    p1, q1 = F(a[0]), F(1)
    convs = [(p1, q1)]
    for k in range(1, n):
        p0, q0, p1, q1 = p1, q1, F(a[k]) * p1 + p0, F(a[k]) * q1 + q0
        convs.append((p1, q1))
    # consecutive convergents bracket sqrt 11
    convs = [(p, q) for p, q in convs if p * p - 11 * q * q != 0]
    lo = hi = None
    for p, q in convs:
        v = p / q
        if p * p - 11 * q * q < 0:      # below
            if lo is None or v > lo:
                lo = v
        else:
            if hi is None or v < hi:
                hi = v
    return lo, hi


def sign_proc2(x, maxit=400):
    """sign of the algebraic number x, PROC-2: shrink brackets for sqrt3 and
    sqrt11 until every embedding's value interval excludes 0, then read the
    sign off the identity embedding."""
    x = alg(x)
    if x.is_zero():
        return 0
    for n in (8, 16, 32, 64, 128, 256):
        l3, h3 = brackets_sqrt3_iters(n + 4)
        l11, h11 = brackets_sqrt11_cf(max(4, n // 2))
        embs = x.embeds()
        # evaluate each embedding with interval arithmetic in (sqrt3,sqrt11)
        vals = []
        for (a, b, c, d) in embs:
            acc = [a, a]
            for coef, (l, h) in ((b, (l3, h3)), (c, (l11, h11))):
                if coef >= 0:
                    acc = [acc[0] + coef * l, acc[1] + coef * h]
                else:
                    acc = [acc[0] + coef * h, acc[1] + coef * l]
            # d term: d*s3*s11*sqrt33 with sqrt33 -> s3*s11*sqrt33; handled as
            # product of brackets for sqrt3 and sqrt11 times sqrt(33):
            l33, h33 = brackets_sqrt3_iters(n + 4)[0] * brackets_sqrt11_cf(max(4, n // 2))[0], \
                brackets_sqrt3_iters(n + 4)[1] * brackets_sqrt11_cf(max(4, n // 2))[1]
            if d >= 0:
                acc = [acc[0] + d * l33, acc[1] + d * h33]
            else:
                acc = [acc[0] + d * h33, acc[1] + d * l33]
            vals.append(acc)
        if all(lo > 0 or hi < 0 for lo, hi in vals):
            lo, hi = vals[0]
            return 1 if lo > 0 else -1
    raise RuntimeError("sign_proc2 did not separate: %r" % (x,))


# --- PROC-1 sign decision: rigorous interval arithmetic with Fractions ------

class Iv(object):
    """closed rational interval, outward rounding."""
    __slots__ = ("lo", "hi")

    def __init__(self, lo, hi=None):
        if hi is None:
            lo, hi = F(lo), F(lo)
        self.lo, self.hi = F(lo), F(hi)

    def __add__(self, o):
        o = iv(o)
        return Iv(self.lo + o.lo, self.hi + o.hi)

    __radd__ = __add__

    def __neg__(self):
        return Iv(-self.hi, -self.lo)

    def __sub__(self, o):
        return self + (-iv(o))

    def __rsub__(self, o):
        return iv(o) - self

    def __mul__(self, o):
        o = iv(o)
        cand = [self.lo * o.lo, self.lo * o.hi, self.hi * o.lo, self.hi * o.hi]
        return Iv(min(cand), max(cand))

    __rmul__ = __mul__

    def __truediv__(self, o):
        o = iv(o)
        assert o.lo > 0 or o.hi < 0
        if o.lo > 0:
            return self * Iv(1 / o.hi, 1 / o.lo)
        return self * Iv(1 / o.hi, 1 / o.lo)

    def contains_zero(self):
        return self.lo <= 0 <= self.hi

    def sign(self):
        assert not self.contains_zero()
        return 1 if self.lo > 0 else -1


def iv(x):
    if isinstance(x, Iv):
        return x
    if isinstance(x, Alg):
        # exact enclosure using the principal brackets
        l3, h3 = brackets_sqrt3_iters(200)
        l11, h11 = brackets_sqrt11_cf(100)
        a, b, c, d = x.c
        acc = Iv(a)
        acc = acc + (Iv(b * l3, b * h3) if b >= 0 else Iv(b * h3, b * l3))
        acc = acc + (Iv(c * l11, c * h11) if c >= 0 else Iv(c * h11, c * l11))
        l33, h33 = l3 * l11, h3 * h11
        acc = acc + (Iv(d * l33, d * h33) if d >= 0 else Iv(d * h33, d * l33))
        return acc
    return Iv(x)


