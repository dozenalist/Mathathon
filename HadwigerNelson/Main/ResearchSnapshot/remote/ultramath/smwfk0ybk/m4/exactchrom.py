"""exactchrom.py -- exact chromatic number of the cell-constant reachability graph of the
hexagonal tiling family, by finite quotients and coset colourings.

For circumradius r the lattice is L*Z[omega] with L = sqrt3 r; the Voronoi cell C is the regular
hexagon of circumradius r.  Two cells C+v, C+w must get different colours iff they can contain a
pair of points at distance exactly 1, which (cellbar.py, and proved in D13.md) happens iff
    dist((v-w)/2, C) <= 1/2   and   |v-w| >= 1-2r.

Lower bound: for any sublattice M of the lattice of finite index N, a proper colouring of the
whole graph induces one of the finite quotient graph on Lattice/M, so chi(graph) >= chi(quotient).
Upper bound: if M has minimum length > 1+2r then the N cosets of M give a proper N-colouring.
Both are exact computations.
"""
from fractions import Fraction as F
from math import sqrt
import json
from q3 import Q3, Pt, q3, SQ3, ZERO, ONE, HALF, hexagon, poly_dist2, lattice_pt
from cellbar import reachable, form

Q = lambda *a: Q3(*a)


def sublattices(index_max):
    """All sublattices of Z^2 of index <= index_max, as (index, gens) with gens = ((a,b),(0,d))."""
    out = []
    for n in range(1, index_max + 1):
        for a in range(1, n + 1):
            if n % a:
                continue
            d = n // a
            for b in range(d):
                out.append((n, ((a, b), (0, d))))
    return out


def quotient_graph(r, gens, n):
    """Adjacency of the reachability graph on Lattice/M, M generated by (a,b) and (0,d).
    Cosets are represented by the pairs (i,j) with 0 <= i < a, 0 <= j < d; adding the offset
    (p,q) is (i+p, j+q) reduced by the HNF: i' = (i+p) mod a, j' = (j+q - s b) mod d with
    s = (i+p-i')/a."""
    (a, b), (_, d) = gens
    verts = [(i, j) for i in range(a) for j in range(d)]
    adj = {v: set() for v in verts}

    def reduce_add(i, j, p, q):
        t = i + p
        i2 = t % a
        s = (t - i2) // a
        return (i2, (j + q - s * b) % d)

    R = ONE + Q3(2) * q3(r)
    span = a + d + 4
    for p in range(-span, span + 1):
        for q_ in range(-span, span + 1):
            if p == 0 and q_ == 0:
                continue
            v = lattice_pt(p, q_, r)
            if v.norm2() > R * R:
                continue
            if not reachable(v, r):
                continue
            for (i, j) in verts:
                adj[(i, j)].add(reduce_add(i, j, p, q_))
    return verts, adj


def chi_exact(verts, adj):
    """Exact chromatic number by DSATUR branch and bound.  Graphs here have <= 30 vertices."""
    n = len(verts)
    if n == 0:
        return 0
    order = {v: k for k, v in enumerate(verts)}
    nb = [set(order[w] for w in adj[v]) for v in verts]
    best = [n + 1]

    def greedy_upper():
        col = [-1] * n
        for v in sorted(range(n), key=lambda x: -len(nb[x])):
            used = {col[u] for u in nb[v] if col[u] >= 0}
            c = 0
            while c in used:
                c += 1
            col[v] = c
        return max(col) + 1

    best[0] = greedy_upper()

    col = [-1] * n

    def rec(v, used_colours):
        if used_colours >= best[0]:
            return
        if v == n:
            best[0] = used_colours
            return
        # DSATUR: choose uncoloured vertex with most distinct neighbour colours
        bestv, bestsat = -1, -1
        for u in range(n):
            if col[u] >= 0:
                continue
            sat = len({col[w] for w in nb[u] if col[w] >= 0})
            if sat > bestsat or (sat == bestsat and len(nb[u]) > len(nb[bestv] if bestv >= 0 else [])):
                bestv, bestsat = u, sat
        v = bestv
        used = {col[w] for w in nb[v] if col[w] >= 0}
        for c in range(used_colours + 1):
            if c in used:
                continue
            col[v] = c
            rec(v + 1, max(used_colours, c + 1))
            col[v] = -1

    rec(0, 0)
    return best[0]


def main():
    r0 = 1 / (sqrt(21) - 2)
    crit = 2 - sqrt(3)
    subs = sublattices(20)
    out = {"r0": r0, "2-sqrt3": crit, "table": []}
    for rnum in [F(2, 5), F(9, 20), F(49, 100), F(19, 50), F(3, 10), F(1, 4), F(1, 5), F(1, 8), F(1, 10)]:
        r = q3(rnum)
        lower = 0
        lb_from = None
        for (n, gens) in subs:
            verts, adj = quotient_graph(r, gens, n)
            c = chi_exact(verts, adj)
            if c > lower:
                lower, lb_from = c, (n, gens)
        target = (ONE + Q3(2) * r) * (ONE + Q3(2) * r) / (Q3(3) * r * r)
        tf = target.float()
        upper, ub_from = None, None
        for (n, gens) in subs:
            (a, b), (_, d) = gens
            mn = None
            K = int((4 * n) ** 0.5) + 4
            for s in range(-K, K + 1):
                for t in range(-K, K + 1):
                    if s == 0 and t == 0:
                        continue
                    x = s * a
                    y = s * b + t * d
                    q = form(x, y)
                    if mn is None or q < mn:
                        mn = q
            if mn > tf:
                upper, ub_from = n, (gens, mn)
                break
        out["table"].append({"r": str(rnum), "r_float": float(rnum),
                             "chi_lower": lower, "lower_from_index": lb_from,
                             "chi_upper": upper, "upper_from": ub_from,
                             "exact": (upper is not None and lower == upper)})
        print(f"r={float(rnum):.4f}  chi >= {lower} (index {lb_from[0] if lb_from else None})"
              f"   chi <= {upper} (index {ub_from[0] if ub_from else None})", flush=True)
    with open("exactchrom_results.json", "w") as f:
        json.dump(out, f, indent=1, default=str)


if __name__ == "__main__":
    main()
